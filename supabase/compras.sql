-- Compras de las casas (Paola, Abue y Casita). Ejecuta en Supabase → SQL Editor. Es seguro repetirlo.
create table if not exists public.compras_productos (
  id           bigint generated always as identity primary key,
  nombre       text not null,
  nombre_norm  text generated always as (regexp_replace(translate(lower(trim(nombre)), 'áéíóúüñ', 'aeiouun'), '\s+', ' ', 'g')) stored,
  categoria    text not null default 'Otros',
  periodo_dias integer not null default 30 check (periodo_dias between 1 and 730),
  basico       boolean not null default false,
  alias        text not null default '',
  creado       timestamptz not null default now()
);
create unique index if not exists compras_productos_norm on public.compras_productos (nombre_norm);

create table if not exists public.compras_items (
  casa           text   not null check (casa in ('paola','abue','casita')),
  producto_id    bigint not null references public.compras_productos(id) on delete cascade,
  fijo           boolean not null default false,   -- está en la lista fija de la casa
  pendiente      boolean not null default false,   -- marcado a mano como pendiente de compra
  periodo_dias   integer check (periodo_dias is null or periodo_dias between 1 and 730),  -- si esa casa gasta distinto al estándar
  periodos       integer not null default 1,       -- para cuántos periodos se compró la última vez
  ultima_compra  date,
  cubre_hasta    date,                             -- hasta cuándo alcanza lo comprado
  precio         numeric check (precio is null or (precio >= 0 and precio <= 100000000)),
  nota           text not null default '',
  posponer_hasta date,                             -- «ahora no»: no avisar hasta esta fecha
  primary key (casa, producto_id)
);

create table if not exists public.compras_historial (
  id          bigint generated always as identity primary key,
  casa        text    not null,
  producto_id bigint  not null references public.compras_productos(id) on delete cascade,
  fecha       date    not null,
  periodos    integer not null,
  precio      numeric,
  prev        jsonb   not null default '{}'::jsonb,   -- estado anterior, para poder deshacer
  creado      timestamptz not null default now()
);
create index if not exists compras_historial_casa on public.compras_historial (casa, creado desc);

alter table public.compras_productos enable row level security;
alter table public.compras_items     enable row level security;
alter table public.compras_historial enable row level security;   -- sin políticas: solo se accede desde el servidor

